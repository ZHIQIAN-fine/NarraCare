"""R2.6 T3 — LLM-as-Judge: gpt-4o-mini scoring on 60 narrative samples.

Scores each sample on 4 axes (1–5 Likert):
  Ax1 — Tone consistency   (does prompt match the labeled tone?)
  Ax2 — Context grounding  (does prompt reference the user's state?)
  Ax3 — Empathy            (does the prompt show care/understanding?)
  Ax4 — Actionability      (does the prompt drive the user to act?)

Retry: up to 3 attempts per sample with exponential backoff.
"""
import sys, json, time, os, logging, re
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))
logging.basicConfig(level=logging.WARNING)

RESULTS_DIR = PROJECT_ROOT / "evaluation" / "results"

# ═════════════════════════════════════════════════════════════════════════
#  Load samples
# ═════════════════════════════════════════════════════════════════════════
samples_path = RESULTS_DIR / "narrative_samples_60.json"
with open(samples_path) as f:
    samples = json.load(f)
print(f"Loaded {len(samples)} samples from {samples_path.name}")

# ═════════════════════════════════════════════════════════════════════════
#  OpenAI client
# ═════════════════════════════════════════════════════════════════════════
try:
    from openai import OpenAI
except ImportError:
    print("Installing openai...")
    import subprocess
    subprocess.check_call([sys.executable, "-m", "pip", "install", "openai", "-q"])
    from openai import OpenAI

api_key = os.environ.get("OPENAI_API_KEY", "")
if not api_key:
    # Try reading from file
    key_path = PROJECT_ROOT / ".openai_key"
    if key_path.exists():
        api_key = key_path.read_text().strip()
if not api_key:
    print("ERROR: No OpenAI API key found. Set OPENAI_API_KEY or create .openai_key")
    sys.exit(1)

client = OpenAI(api_key=api_key)

# ═════════════════════════════════════════════════════════════════════════
#  Scoring prompt template
# ═════════════════════════════════════════════════════════════════════════
SYSTEM_PROMPT = """You are an expert evaluator for a healthcare rehabilitation chatbot.
You will be given a prompt generated by the chatbot's narrator module along with context
about the user's state (pain level, fatigue, task difficulty, emotional state, tone).

Score the prompt on 4 axes using a 1–5 Likert scale:

Ax1 — Tone Consistency: Does the prompt match the intended tone?
  1=completely wrong tone  3=acceptable  5=perfectly consistent

Ax2 — Context Grounding: Does the prompt reference or reflect the user's current state
  (pain, fatigue, difficulty, emotional level)?
  1=generic/no reference  3=some grounding  5=deeply personalized

Ax3 — Empathy: Does the prompt show genuine care and understanding?
  1=robotic/dismissive  3=polite  5=warm and supportive

Ax4 — Actionability: Does the prompt encourage the user to take a next step?
  1=no direction  3=mild suggestion  5=clear motivating call-to-action

Respond ONLY with a JSON object (no markdown, no explanation):
{"Ax1": <int>, "Ax2": <int>, "Ax3": <int>, "Ax4": <int>}"""


def build_user_prompt(sample: dict) -> str:
    return f"""Context:
- User pain level: {sample.get('user_pain', '?')}/10
- User fatigue level: {sample.get('user_fatigue', '?')}/10
- Task: {sample.get('task_name', '?')} (difficulty {sample.get('task_difficulty', '?')}, category: {sample.get('task_category', '?')})
- Emotional state: {sample.get('emotional_state_level', 'normal')}
- Intended tone: {sample.get('tone', '?')}
- Scenario: {sample.get('scenario', '?')}
- Safety blocked today: {sample.get('safety_blocked_today', False)}

Prompt to evaluate:
\"\"\"{sample.get('prompt_text', '(empty)')}\"\"\""""


# ═════════════════════════════════════════════════════════════════════════
#  Score with retry
# ═════════════════════════════════════════════════════════════════════════
def score_sample(sample: dict, max_retries: int = 3) -> dict:
    user_msg = build_user_prompt(sample)

    for attempt in range(max_retries):
        try:
            resp = client.chat.completions.create(
                model="gpt-4o-mini",
                messages=[
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": user_msg},
                ],
                temperature=0.0,
                max_tokens=100,
            )
            text = resp.choices[0].message.content.strip()
            # Parse JSON (handle possible markdown wrapping)
            text = re.sub(r"^```json\s*", "", text)
            text = re.sub(r"\s*```$", "", text)
            scores = json.loads(text)
            # Validate
            for ax in ["Ax1", "Ax2", "Ax3", "Ax4"]:
                assert ax in scores, f"Missing {ax}"
                assert 1 <= scores[ax] <= 5, f"{ax}={scores[ax]} out of range"
            return {"scores": scores, "raw_response": text, "attempts": attempt + 1}

        except Exception as e:
            if attempt < max_retries - 1:
                wait = 2 ** (attempt + 1)
                print(f"    Retry {attempt+1} for {sample['sample_id']}: {e}. "
                      f"Waiting {wait}s...")
                time.sleep(wait)
            else:
                print(f"    FAILED after {max_retries} attempts: {sample['sample_id']}: {e}")
                return {"scores": None, "raw_response": str(e),
                        "attempts": max_retries, "error": True}


# ═════════════════════════════════════════════════════════════════════════
#  Main loop
# ═════════════════════════════════════════════════════════════════════════
print(f"\n{'='*64}")
print(f"[R2.6 T3] LLM-as-Judge — gpt-4o-mini scoring")
print(f"  {len(samples)} samples, 4 axes each")
print(f"  Start: {time.strftime('%Y-%m-%d %H:%M:%S')}")
print(f"{'='*64}")

scored = []
for i, sample in enumerate(samples):
    print(f"  [{i+1:2d}/{len(samples)}] {sample['sample_id'][:40]}...", end=" ", flush=True)
    result = score_sample(sample)
    scored.append({
        "sample_id": sample["sample_id"],
        "stream_label": sample["stream_label"],
        **result,
    })
    if result.get("scores"):
        s = result["scores"]
        print(f"Ax1={s['Ax1']} Ax2={s['Ax2']} Ax3={s['Ax3']} Ax4={s['Ax4']}")
    else:
        print("ERROR")

# ═════════════════════════════════════════════════════════════════════════
#  Save
# ═════════════════════════════════════════════════════════════════════════
n_ok = sum(1 for s in scored if s.get("scores"))
n_fail = sum(1 for s in scored if s.get("error"))
print(f"\n  Scored: {n_ok}/{len(scored)} (failed: {n_fail})")

out_path = RESULTS_DIR / "narrative_llm_scores_60.json"
with open(out_path, "w") as f:
    json.dump(scored, f, indent=2)
print(f"✓ Saved: {out_path.name}")
